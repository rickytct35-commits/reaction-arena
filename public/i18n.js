function detectLang() {
  const saved = localStorage.getItem('ra_lang');
  if (saved && I18N[saved]) return saved;
  const nav = (navigator.language || 'zh-TW').toLowerCase();
  if (nav.startsWith('zh')) {
    if (nav.includes('cn') || nav.includes('hans') || nav.includes('sg')) return 'zh-CN';
    return 'zh-TW';
  }
  if (nav.startsWith('en')) return 'en';
  return 'zh-TW';
}

let currentLang = detectLang();

function t(key, vars) {
  let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
  if (vars && typeof vars === 'object') {
    s = String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : '{' + k + '}'));
  }
  return s;
}

function setLang(code) {
  if (!I18N[code]) return;
  currentLang = code;
  localStorage.setItem('ra_lang', code);
  document.documentElement.lang = code;
  if (window.onLangChange) window.onLangChange();
}
